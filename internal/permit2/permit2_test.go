func sampleAuth() Authorization {
	return Authorization{From: "0x7E5F4552091A69125d5DfCb7b8C2659029395Bdf",
		Permitted: Permissions{Token: "0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913", Amount: "1000000"},
		Spender:   UptoProxy, Nonce: "0x" + strings.Repeat("01", 32), Deadline: "1780000660",
		Witness: Witness{To: "0x1111111111111111111111111111111111111111", Facilitator: "0x2222222222222222222222222222222222222222", ValidAfter: "0"}}
}
func TestPermit2GoldenAndTamper(t *testing.T) {
	a := sampleAuth()
	td, err := TypedData(8453, a)
	if err != nil {
		t.Fatal(err)
	}
	digest, _, err := apitypes.TypedDataAndHash(td)
	if err != nil {
		t.Fatal(err)
	}
	// Independently generated by viem's hashTypedData (web test same fixture).
	if hex.EncodeToString(digest) != "9fad5427c44d501d46fd96ba1cef992c704c745d3c475eae7b554bb04d19d83f" {
		t.Fatalf("typed-data interoperability mismatch: %x", digest)
	}
	key, _ := crypto.HexToECDSA(strings.Repeat("0", 63) + "1")
	p, err := Sign(key, 8453, a)
	if err != nil {
		t.Fatal(err)
	}
	if err = Verify(8453, p); err != nil {
		t.Fatal(err)
	}
	wantNonce, _ := Uint256(a.Nonce)
	if p.Authorization.Nonce != wantNonce.String() || strings.HasPrefix(p.Authorization.Nonce, "0x") {
		t.Fatal("wire nonce must be a decimal uint256 without changing its signed value")
	}
	if Verify(1, p) == nil {
		t.Fatal("wrong chain accepted")
	}
	for name, change := range map[string]func(*Authorization){
		"ceiling":     func(a *Authorization) { a.Permitted.Amount = "999999" },
		"nonce":       func(a *Authorization) { a.Nonce = "2" },
		"deadline":    func(a *Authorization) { a.Deadline = "1780000999" },
		"recipient":   func(a *Authorization) { a.Witness.To = a.From },
		"facilitator": func(a *Authorization) { a.Witness.Facilitator = a.From },
		"token":       func(a *Authorization) { a.Permitted.Token = a.From },
		"spender":     func(a *Authorization) { a.Spender = Address },
	} {
		t.Run(name, func(t *testing.T) {
			tampered := p
			change(&tampered.Authorization)
			if Verify(8453, tampered) == nil {
				t.Fatal("tampered signature accepted")
			}
		})
	}
}
func TestUint256RejectsMalformed(t *testing.T) {
	for _, s := range []string{"", "-1", "+1", "1.5", "NaN", "0x", strings.Repeat("f", 65), "0x" + strings.Repeat("f", 65)} {
		if _, err := Uint256(s); err == nil {
			t.Fatalf("accepted %q", s)
		}
	}
}
func callData(a Authorization, amount int64) []byte {
	cap, _ := Uint256(a.Permitted.Amount)
	nonce, _ := Uint256(a.Nonce)
	deadline, _ := Uint256(a.Deadline)
	words := [][]byte{common.HexToAddress(a.Permitted.Token).Bytes(), cap.Bytes(), nonce.Bytes(), deadline.Bytes(),
		big.NewInt(amount).Bytes(), common.HexToAddress(a.From).Bytes(), common.HexToAddress(a.Witness.To).Bytes(),
		common.HexToAddress(a.Witness.Facilitator).Bytes(), {}, big.NewInt(320).Bytes(), big.NewInt(65).Bytes()}
	data := crypto.Keccak256([]byte("settle(((address,uint256),uint256,uint256),uint256,address,(address,address,uint256),bytes)"))[:4]
	for _, word := range words {
		data = append(data, common.LeftPadBytes(word, 32)...)
	}
	return append(data, make([]byte, 96)...)
}
func TestSettlementCallRejectsOldNonceAndOtherCharge(t *testing.T) {
	a := sampleAuth()
	data := callData(a, 55000)
	if err := CheckSettlementCall(data, a, big.NewInt(55000)); err != nil {
		t.Fatal(err)
	}
	if CheckSettlementCall(data, a, big.NewInt(1000000)) == nil {
		t.Fatal("full-ceiling charge accepted as partial")
	}
	a.Nonce = "2"
	if CheckSettlementCall(data, a, big.NewInt(55000)) == nil {
		t.Fatal("old payment reused for different nonce")
	}
}

func TestSettlementWithPermitBindsTheSameAuthorization(t *testing.T) {
	a := sampleAuth()
	data := callData(a, 55000)
	withPermit := crypto.Keccak256([]byte("settleWithPermit((uint256,uint256,bytes32,bytes32,uint8),((address,uint256),uint256,uint256),uint256,address,(address,address,uint256),bytes)"))[:4]
	withPermit = append(withPermit, make([]byte, 5*32)...)
	withPermit = append(withPermit, data[4:]...)
	if err := CheckSettlementCall(withPermit, a, big.NewInt(55000)); err != nil {
		t.Fatal(err)
	}
	a.Nonce = "2"
	if CheckSettlementCall(withPermit, a, big.NewInt(55000)) == nil {
		t.Fatal("old settleWithPermit transaction accepted")
	}
}

func TestVerifySettlementRejectsInvalidHashAndAmountBeforeRPC(t *testing.T) {
	a := sampleAuth()
	for _, hash := range []string{"local:fake", "0x" + strings.Repeat("g", 64), "0x" + strings.Repeat("0", 64)} {
		if VerifySettlement(context.Background(), "invalid", hash, a, big.NewInt(1)) == nil {
			t.Fatal("invalid hash accepted")
		}
	}
	for _, amount := range []*big.Int{nil, big.NewInt(-1), big.NewInt(0)} {
		if CheckTransferReceipt(nil, "", a, amount) == nil {
			t.Fatal("invalid amount accepted")
		}
	}
}
func receiptFixture(a Authorization, hash common.Hash) *ethTypes.Receipt {
	return &ethTypes.Receipt{Status: 1, BlockNumber: big.NewInt(123), TxHash: hash, Logs: []*ethTypes.Log{{
		Address: common.HexToAddress(a.Permitted.Token),
		Topics:  []common.Hash{crypto.Keccak256Hash([]byte("Transfer(address,address,uint256)")), common.HexToHash(a.From), common.HexToHash(a.Witness.To)},
		Data:    common.LeftPadBytes(big.NewInt(55000).Bytes(), 32),
	}}}
}
func TestReceiptRequiresRealMatchingTransfer(t *testing.T) {
	a := sampleAuth()
	hash := common.HexToHash("0x" + strings.Repeat("1", 64))
	for name, change := range map[string]func(*ethTypes.Receipt){
		"valid":            func(*ethTypes.Receipt) {},
		"reverted":         func(r *ethTypes.Receipt) { r.Status = 0 },
		"pending":          func(r *ethTypes.Receipt) { r.BlockNumber = nil },
		"missing_transfer": func(r *ethTypes.Receipt) { r.Logs = nil },
		"wrong_token":      func(r *ethTypes.Receipt) { r.Logs[0].Address = common.HexToAddress(Address) },
		"wrong_payee":      func(r *ethTypes.Receipt) { r.Logs[0].Topics[2] = common.Hash{} },
		"wrong_amount":     func(r *ethTypes.Receipt) { r.Logs[0].Data = common.LeftPadBytes(big.NewInt(1000000).Bytes(), 32) },
		"reorg":            func(r *ethTypes.Receipt) { r.Logs[0].Removed = true },
	} {
		t.Run(name, func(t *testing.T) {
			r := receiptFixture(a, hash)
			change(r)
			err := CheckTransferReceipt(r, hash.Hex(), a, big.NewInt(55000))
			if (err == nil) != (name == "valid") {
				t.Fatalf("err=%v", err)
			}
		})
	}
}
func TestVerifySettlementReadOnlyRPC(t *testing.T) {
	a := sampleAuth()
	key, _ := crypto.HexToECDSA(strings.Repeat("0", 63) + "2")
	a.Witness.Facilitator = crypto.PubkeyToAddress(key.PublicKey).Hex()
	proxy := common.HexToAddress(UptoProxy)
	tx, err := ethTypes.SignTx(ethTypes.NewTx(&ethTypes.LegacyTx{Nonce: 1, To: &proxy, Gas: 300000, GasPrice: big.NewInt(1), Data: callData(a, 55000)}), ethTypes.NewEIP155Signer(big.NewInt(8453)), key)
	if err != nil {
		t.Fatal(err)
	}
	receipt := receiptFixture(a, tx.Hash())
	receiptReads := 0
	rpc := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		var req struct{ Method string }
		json.NewDecoder(r.Body).Decode(&req)
		var result any
		switch req.Method {
		case "eth_chainId":
			result = "0x2105"
		case "eth_getTransactionReceipt":
			receiptReads++
			if receiptReads > 1 {
				result = receipt
			}
		case "eth_getTransactionByHash":
			result = tx
		default:
			t.Errorf("unexpected RPC %s", req.Method)
		}
		json.NewEncoder(w).Encode(map[string]any{"jsonrpc": "2.0", "id": 1, "result": result})
	}))
	defer rpc.Close()
	if err := VerifySettlement(context.Background(), rpc.URL, tx.Hash().Hex(), a, big.NewInt(55000)); err != nil {
		t.Fatal(err)
	}
	if receiptReads != 2 {
		t.Fatal("pending receipt was not reconciled using read-only queries", receiptReads)
	}
	a.Nonce = "2"
	if VerifySettlement(context.Background(), rpc.URL, tx.Hash().Hex(), a, big.NewInt(55000)) == nil {
		t.Fatal("unrelated transaction accepted")
	}
}
